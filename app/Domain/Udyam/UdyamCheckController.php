    use Respond;

    private CheckUdyamCombinationAction $checkAction;

    public function __construct(CheckUdyamCombinationAction $checkAction)
    {
        $this->checkAction = $checkAction;
    }

    /**
     * Handle the Udyam combination verification request.
     *
     * @param Request $request
     * @return \Illuminate\Http\JsonResponse
     */
    public function __invoke(Request $request)
    {
        // If it's a GET request and single parameters are provided, check that single combination
        if ($request->isMethod('get') && $request->has(['udyam', 'mobile'])) {
            $udyam = (string) $request->query('udyam');
            $mobile = (string) $request->query('mobile');

            $result = $this->checkAction->check($udyam, $mobile);

            $existsCount = 0;
            $tradingCount = 0;
            $mediumCount = 0;

            if (!empty($result['exists'])) {
                $existsCount = 1;
                if (stripos($result['major_activity'] ?? '', 'Trading') !== false) {
                    $tradingCount = 1;
                }
                if (stripos($result['enterprise_type'] ?? '', 'Medium') !== false) {
                    $mediumCount = 1;
                }
            }

            return $this->success(
                data: [
                    'results' => [
                        $udyam => $result
                    ],
                    'summary' => [
                        'total_checked' => 1,
                        'exists_count' => $existsCount,
                        'trading_activity_count' => $tradingCount,
                        'medium_enterprise_count' => $mediumCount,
                    ]
                ],
                message: 'Udyam combination verification completed.'
            );
        }

        // Otherwise, expect multiple combinations
        // If payload is empty or not provided, we can fallback to the test combinations for ease of use
        $combinations = $request->input('combinations');
        if (empty($combinations) || !is_array($combinations)) {
            $combinations = $this->getCombinations();
        }

        return new \Symfony\Component\HttpFoundation\StreamedResponse(function () use ($combinations) {
            // Disable output buffering
            if (ob_get_level() > 0) {
                ob_end_clean();
            }

            // Headers to prevent caching and set content type
            header('Content-Type: application/x-ndjson');
            header('Cache-Control: no-cache');
            header('Connection: keep-alive');

            $totalChecked = count($combinations);
            $existsCount = 0;
            $tradingCount = 0;
            $mediumCount = 0;

            foreach ($combinations as $udyamNo => $mobile) {
                $res = $this->checkAction->check((string) $udyamNo, (string) $mobile);

                if (!empty($res['exists'])) {
                    $existsCount++;
                    if (stripos($res['major_activity'] ?? '', 'Trading') !== false) {
                        $tradingCount++;
                    }
                    if (stripos($res['enterprise_type'] ?? '', 'Medium') !== false) {
                        $mediumCount++;
                    }
                }

                // Output the result line immediately
                echo json_encode([
                    'type' => 'result',
                    'udyam' => $udyamNo,
                    'data' => $res
                ]) . "\n";

                // Flush the buffer
                flush();
            }

            // Finally output the summary stats
            echo json_encode([
                'type' => 'summary',
                'data' => [
                    'total_checked' => $totalChecked,
                    'exists_count' => $existsCount,
                    'trading_activity_count' => $tradingCount,
                    'medium_enterprise_count' => $mediumCount,
                ]
            ]) . "\n";
            flush();
        });
    }

